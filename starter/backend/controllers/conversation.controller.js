import mongoose from "mongoose";
import Conversation from "../models/conversation.model.js";
import Message from "../models/message.model.js";
import { parsePagination, paginationMeta } from "../utils/pagination.js";
import { notFound, badRequest } from "../utils/httpError.js";
import { claimConversation, setConversationStatus } from "../services/conversation.service.js";
import { enqueueReply } from "../services/message.service.js";

// GET /api/conversations?workspace=<id>&page=1&limit=20
export const listConversations = async (req, res) => {
  const pagination = parsePagination(req.query);
  const filter = { workspaceId: req.workspaceId };

  const [conversations, total] = await Promise.all([
    Conversation.find(filter)
      // _id breaks ties so the order is stable between pages.
      .sort({ lastMessageAt: -1, _id: -1 })
      .skip(pagination.skip)
      .limit(pagination.limit)
      .lean(),
    Conversation.countDocuments(filter),
  ]);

  res.json({ conversations, pagination: paginationMeta(pagination, total) });
};

// GET /api/conversations/:conversationId/messages?workspace=<id>
export const getConversationMessages = async (req, res) => {
  const { conversationId } = req.params;

  if (!mongoose.isValidObjectId(conversationId)) throw notFound("Conversation not found");

  // Filtering by workspaceId as well as _id means a conversation from another
  // workspace looks exactly like one that doesn't exist (404, nothing leaked).
  const conversation = await Conversation.findOne({
    _id: conversationId,
    workspaceId: req.workspaceId,
  }).lean();

  if (!conversation) throw notFound("Conversation not found");

  const messages = await Message.find({
    workspaceId: req.workspaceId,
    conversationId: conversation._id,
  })
    .sort({ occurredAt: 1, _id: 1 }) // oldest first by when it happened, as a chat reads
    .lean();

  res.json({ conversation, messages });
};

// Loads a conversation by id within req.workspaceId, or throws 404.
const findConversation = async (req) => {
  const { conversationId } = req.params;
  if (!mongoose.isValidObjectId(conversationId)) throw notFound("Conversation not found");

  const conversation = await Conversation.findOne({
    _id: conversationId,
    workspaceId: req.workspaceId,
  }).lean();

  if (!conversation) throw notFound("Conversation not found");
  return conversation;
};

// POST /api/conversations/:conversationId/claim?workspace=<id>
// Same code path as /__grader/claim; the agent is the signed-in user.
export const claimConversationForMe = async (req, res) => {
  const { contact } = await findConversation(req);
  const { claimed, conversation } = await claimConversation({
    workspaceId: req.workspaceId,
    contact,
    agent: req.user.sub,
  });

  res.status(claimed ? 200 : 409).json({ conversation });
};

// POST /api/conversations/:conversationId/close?workspace=<id>
// POST /api/conversations/:conversationId/reopen?workspace=<id>
export const changeStatus = (status) => async (req, res) => {
  const { _id } = await findConversation(req);
  const conversation = await setConversationStatus({
    workspaceId: req.workspaceId,
    conversationId: _id,
    status,
  });

  res.json({ conversation });
};

// POST /api/conversations/:conversationId/messages?workspace=<id>  { text, client_ref }
// client_ref is generated by the browser, so a retried request is the same reply.
export const replyToConversation = async (req, res) => {
  const { text, client_ref: clientRef } = req.body ?? {};

  if (typeof text !== "string" || !text.trim() || text.length > 4000) {
    throw badRequest("text must be a non-empty string of at most 4000 characters");
  }
  if (typeof clientRef !== "string" || !clientRef.trim() || clientRef.length > 200) {
    throw badRequest("client_ref must be a non-empty string of at most 200 characters");
  }

  const { contact } = await findConversation(req);
  const { message, created } = await enqueueReply({
    workspaceId: req.workspaceId,
    contact,
    text: text.trim(),
    clientRef: clientRef.trim(),
    senderId: req.user.sub,
  });

  res.status(202).json({ message, duplicate: !created });
};
